// composeFiles are the names docker compose looks for, in its order.
var composeFiles = []string{"compose.yaml", "compose.yml", "docker-compose.yaml", "docker-compose.yml"}

const generatedHeader = `# Generated by ctm. Review this model and commit it next to your code.
#
# Next steps:
#   1. Classify your data under "data:" and reference it from flows ("data:")
#      and datastores ("stores:"). Data-sensitivity rules only fire on
#      classified data.
#   2. Add facts the source cannot express, e.g. properties.authentication,
#      properties.logging, properties.encryptionAtRest, flow "authenticated".
#   3. Run: ctm analyze
#
# Schema: https://github.com/clebeer/carbon-threat/blob/main/schema/ctm-v1.json
`

func newExtractCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "extract",
		Short: "Generate a model from infrastructure definitions",
	}
	var output string
	composeCmd := &cobra.Command{
		Use:   "compose [file]",
		Short: "Generate a model from a Docker Compose file",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			path := ""
			if len(args) == 1 {
				path = args[0]
			} else {
				path = findCompose(".")
				if path == "" {
					return &ExitError{Code: ExitFailure, Err: errors.New("no compose file found in the current directory")}
				}
			}
			out, warnings, err := extractCompose(path)
			if err != nil {
				return &ExitError{Code: ExitFailure, Err: err}
			}
			for _, w := range warnings {
				fmt.Fprintln(cmd.ErrOrStderr(), "warning:", w)
			}
			w, closeFn, err := openOutput(cmd, output)
			if err != nil {
				return &ExitError{Code: ExitFailure, Err: err}
			}
			_, err = w.Write(out)
			if cerr := closeFn(); err == nil {
				err = cerr
			}
			if err != nil {
				return &ExitError{Code: ExitFailure, Err: err}
			}
			return nil
		},
	}
	composeCmd.Flags().StringVarP(&output, "output", "o", "", "write the model to a file instead of stdout")
	cmd.AddCommand(composeCmd)
	return cmd
}

func extractCompose(path string) ([]byte, []string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, nil, err
	}
	m, warnings, err := compose.Extract(data, path)
	if err != nil {
		return nil, nil, err
	}
	out, err := compose.Marshal(m)
	if err != nil {
		return nil, nil, err
	}
	return append([]byte(generatedHeader+"\n"), out...), warnings, nil
}

func findCompose(dir string) string {
	for _, name := range composeFiles {
		p := filepath.Join(dir, name)
		if _, err := os.Stat(p); err == nil {
			return p
		}
	}
	return ""
}

