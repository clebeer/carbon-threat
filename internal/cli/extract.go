func newInitCmd() *cobra.Command {
	var force bool
	cmd := &cobra.Command{
		Use:   "init [dir]",
		Short: "Create threatmodel.yaml, generated from the project when possible",
		Long: `Create threatmodel.yaml in dir (default: current directory).

If a Docker Compose file is present the model is generated from it;
otherwise a small example model is written for you to edit.`,
		Args: cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			dir := "."
			if len(args) == 1 {
				dir = args[0]
			}
			target := filepath.Join(dir, DefaultModelFile)
			if _, err := os.Stat(target); err == nil && !force {
				return &ExitError{Code: ExitFailure, Err: fmt.Errorf("%s already exists (use --force to overwrite)", target)}
			} else if err != nil && !errors.Is(err, fs.ErrNotExist) {
				return &ExitError{Code: ExitFailure, Err: err}
			}

			var content []byte
			if src := findCompose(dir); src != "" {
				out, warnings, err := extractCompose(src)
				if err != nil {
					return &ExitError{Code: ExitFailure, Err: err}
				}
				for _, w := range warnings {
					fmt.Fprintln(cmd.ErrOrStderr(), "warning:", w)
				}
				content = out
				fmt.Fprintf(cmd.OutOrStdout(), "Generated %s from %s.\n", target, src)
			} else {
				name := "my-system"
				if abs, err := filepath.Abs(dir); err == nil {
					name = filepath.Base(abs)
				}
				content = []byte(fmt.Sprintf(skeleton, name))
				fmt.Fprintf(cmd.OutOrStdout(), "No supported source found; wrote an example model to %s.\n", target)
			}
			if err := os.WriteFile(target, content, 0o644); err != nil {
				return &ExitError{Code: ExitFailure, Err: err}
			}
			fmt.Fprintln(cmd.OutOrStdout(), "Next: classify your data in the model, then run `ctm analyze`.")
			return nil
		},
	}
	cmd.Flags().BoolVar(&force, "force", false, "overwrite an existing threatmodel.yaml")
	return cmd
}
